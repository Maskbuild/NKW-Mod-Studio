function toolTiers(ctx: GenCtx, mats: ToolMatIR[]): string {
  const { p, pkg } = ctx
  const j = new JavaFile(pkg, 'ModToolTiers')
  if (p.toolApi === 'toolMaterial') {
    j.use(MC.ToolMaterial, MC.BlockTags)
    return j.render(`
public final class ModToolTiers {
${mats
  .map((m) => `    public static final ToolMaterial ${C(m.id)} = new ToolMaterial(BlockTags.${LEVEL_TAG[m.level]}, ${m.durability}, ${f(m.speed)}, ${f(m.damage)}, ${m.enchantability}, NkwTags.TOOL_${C(m.id)});`)
  .join('\n')}

    private ModToolTiers() {}
}`)
  }
  j.use(MC.Tier, MC.Ingredient, MC.Supplier)
  const tagMode = p.toolApi === 'tierTag'
  if (tagMode) j.use(MC.BlockTags, MC.TagKey, MC.Block)
  const consts = mats
    .map((m) => {
      const lvl = tagMode ? `BlockTags.${LEVEL_TAG[m.level]}` : String(LEVEL_NUM[m.level])
      return `    ${C(m.id)}(${lvl}, ${m.durability}, ${f(m.speed)}, ${f(m.damage)}, ${m.enchantability}, () -> Ingredient.of(NkwTags.TOOL_${C(m.id)}))`
    })
    .join(',\n')
  const lvlType = tagMode ? 'TagKey<Block>' : 'int'
  const lvlMethod = tagMode
    ? `    @Override\n    public TagKey<Block> getIncorrectBlocksForDrops() {\n        return level;\n    }`
    : `    @Override\n    public int getLevel() {\n        return level;\n    }`
  return j.render(`
public enum ModToolTiers implements Tier {
${consts};

    private final ${lvlType} level;
    private final int uses;
    private final float speed;
    private final float damage;
    private final int enchantability;
    private final Supplier<Ingredient> repair;

    ModToolTiers(${lvlType} level, int uses, float speed, float damage, int enchantability, Supplier<Ingredient> repair) {
        this.level = level;
        this.uses = uses;
        this.speed = speed;
        this.damage = damage;
        this.enchantability = enchantability;
        this.repair = repair;
    }

    @Override
    public int getUses() {
        return uses;
    }

    @Override
    public float getSpeed() {
        return speed;
    }

    @Override
    public float getAttackDamageBonus() {
        return damage;
    }

${lvlMethod}

    @Override
    public int getEnchantmentValue() {
        return enchantability;
    }

    @Override
    public Ingredient getRepairIngredient() {
        return repair.get();
    }
}`)
}

