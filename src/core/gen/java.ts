export function genJava(ctx: GenCtx): void {
  const { ir, pkg, loader, p, files } = ctx
  const dir = `src/main/java/${pkg.replace(/\./g, '/')}`
  const legacyForge = loader === 'forge' && p.mc === '1.16.5'
  const out = (cls: string, text: string) => files.push({ path: `${dir}/${cls}.java`, text: legacyForge ? toMcp1165(text) : text })
  const fab = fabricLike(loader)
  const forge = loader === 'forge'
  const neo = loader === 'neoforge'
  const deferred = !fab

  /** How a registered object is read from Java: Fabric stores the value, Forge/Neo a holder. */
  const get = (cls: string, id: string) => (deferred ? `${cls}.${C(id)}.get()` : `${cls}.${C(id)}`)
  const regItems = p.builtInRegistries ? 'BuiltInRegistries.ITEM' : 'Registry.ITEM'
  const regBlocks = p.builtInRegistries ? 'BuiltInRegistries.BLOCK' : 'Registry.BLOCK'
  const regSounds = p.builtInRegistries ? 'BuiltInRegistries.SOUND_EVENT' : 'Registry.SOUND_EVENT'
  const regImport = p.builtInRegistries ? MC.BuiltIn : MC.Registry

  const blockItems = ir.blocks.filter((b) => b.hasItem).map((b) => b.id)
  const tabIcons = tabIconItems(ctx)
  const allItemIds = [...ir.items.map((i) => i.id), ...blockItems, ...tabIcons.map((t) => t.id)]
  const modelBlocks = ir.blocks.filter((b) => b.kind === 'model')
  const needsRenderLayer = modelBlocks.length > 0
  const hasGeo = ctx.gecko && ir.items.some((i) => i.armor?.geo)

  // ───────── NkwTags ─────────
  {
    const j = new JavaFile(pkg, 'NkwTags')
    const fields: string[] = []
    const tag = (kind: string, id: string) => {
      const name = `${kind.toUpperCase()}_${C(id)}`
      const path = `repair/${kind}/${id}`
      if (p.mc === '1.16.5') {
        // 1.16.5 has no TagKey; vanilla's ItemTags.bind is private, so use each loader's tag helper.
        j.use(MC.Tag, MC.Item)
        if (fab) {
          j.use('net.fabricmc.fabric.api.tag.TagRegistry')
          fields.push(`    public static final Tag<Item> ${name} = TagRegistry.item(NkwMod.id("${path}"));`)
        } else {
          j.use(MC.ItemTags)
          fields.push(`    public static final Tag.Named<Item> ${name} = ItemTags.createOptional(NkwMod.id("${path}"));`)
        }
      } else {
        j.use(MC.TagKey, MC.Item)
        if (p.builtInRegistries) j.use(MC.Registries)
        else j.use(MC.Registry)
        fields.push(
          `    public static final TagKey<Item> ${name} = TagKey.create(${p.builtInRegistries ? 'Registries.ITEM' : 'Registry.ITEM_REGISTRY'}, NkwMod.id("${path}"));`
        )
      }
    }
    for (const m of ir.toolMats) tag('tool', m.id)
    for (const m of ir.armorMats) tag('armor', m.id)
    out(
      'NkwTags',
      j.render(`
public final class NkwTags {
${fields.join('\n')}

    private NkwTags() {}

    public static void init() {}
}`)
    )
  }

  // ───────── helper item/block classes ─────────
  if (ir.items.some((i) => i.glint)) {
    const j = new JavaFile(pkg, 'NkwFoilItem').use(MC.Item, MC.ItemStack)
    out(
      'NkwFoilItem',
      j.render(`
public class NkwFoilItem extends Item {
    public NkwFoilItem(Item.Properties properties) {
        super(properties);
    }

    @Override
    public boolean isFoil(ItemStack stack) {
        return true;
    }
}`)
    )
  }

  const toolTypes = new Set(ir.items.filter((i) => i.tool).map((i) => i.tool!.type))
  const needsEffects = toolTypes.size > 0 || ir.items.some((i) => i.armor)
  if (needsEffects) {
    const j = new JavaFile(pkg, 'NkwEffect').use(MC.MobEffect, MC.MobEffects, MC.MobEffectInstance, MC.LivingEntity)
    const type = p.stackId ? 'Holder<MobEffect>' : 'MobEffect'
    if (p.stackId) j.use(MC.Holder)
    out(
      'NkwEffect',
      j.render(`
/** A status effect given by an item: on hit (tools) or while worn (armor). */
public final class NkwEffect {
    private final ${type} effect;
    private final int ticks;
    private final int amplifier;
    private final float chance;
    private final boolean particles;
    private final boolean showIcon;

    public NkwEffect(${type} effect, int ticks, int amplifier, float chance, boolean particles, boolean showIcon) {
        this.effect = effect;
        this.ticks = ticks;
        this.amplifier = amplifier;
        this.chance = chance;
        this.particles = particles;
        this.showIcon = showIcon;
    }

    public void apply(LivingEntity target) {
        if (target.getRandom().nextFloat() < chance) target.addEffect(new MobEffectInstance(effect, ticks, amplifier, false, particles, showIcon));
    }

    public void applyWorn(LivingEntity wearer) {
        int duration = effect == MobEffects.NIGHT_VISION ? 260 : 60;
        wearer.addEffect(new MobEffectInstance(effect, duration, amplifier, true, particles, showIcon));
    }
}`)
    )
  }
  for (const tt of toolTypes) {
    const base = TOOL_CLASS[tt]
    const cls = `Nkw${base}`
    const j = new JavaFile(pkg, cls).use(`net.minecraft.world.item.${base}`, MC.Item, MC.ItemStack, MC.LivingEntity)
    let ctor: string
    if (p.toolApi === 'tierLevel') {
      j.use(MC.Tier)
      const dmgT = tt === 'sword' || tt === 'pickaxe' || tt === 'hoe' ? 'int' : 'float'
      ctor = `public ${cls}(Tier tier, ${dmgT} damage, float speed, Item.Properties properties, NkwEffect... effects) {\n        super(tier, damage, speed, properties);\n        this.effects = effects;\n    }`
    } else if (p.toolApi === 'tierTag') {
      j.use(MC.Tier)
      ctor = `public ${cls}(Tier tier, Item.Properties properties, NkwEffect... effects) {\n        super(tier, properties);\n        this.effects = effects;\n    }`
    } else {
      j.use(MC.ToolMaterial)
      ctor = `public ${cls}(ToolMaterial material, float damage, float speed, Item.Properties properties, NkwEffect... effects) {\n        super(material, damage, speed, properties);\n        this.effects = effects;\n    }`
    }
    out(
      cls,
      j.render(`public class ${cls} extends ${base} {
    private final NkwEffect[] effects;

    ${ctor}

    @Override
    public boolean hurtEnemy(ItemStack stack, LivingEntity target, LivingEntity attacker) {
        for (NkwEffect effect : effects) effect.apply(target);
        return super.hurtEnemy(stack, target, attacker);
    }
}`)
    )
  }

  // Armor pieces with worn effects (no GeckoLib model)
  if (ir.items.some((i) => i.armor && i.armor.effects.length && !(ctx.gecko && i.armor.geo))) {
    const at = armorTypes(p.armorApi)
    const j = new JavaFile(pkg, 'NkwArmorItem').use(MC.ArmorItem, MC.Item, ...at.imports, ...WORN_IMPORTS)
    out(
      'NkwArmorItem',
      j.render(`
public class NkwArmorItem extends ArmorItem {
    private final EquipmentSlot wornSlot;
    private final NkwEffect[] effects;

    public NkwArmorItem(${at.mat} material, ${at.slot} type, Item.Properties properties, EquipmentSlot wornSlot, NkwEffect... effects) {
        super(material, type, properties);
        this.wornSlot = wornSlot;
        this.effects = effects;
    }

${wornEffectsMethod()}
}`)
    )
  }

  if (fab && !p.jukeboxSongs && ir.items.some((i) => i.disc)) {
    const j = new JavaFile(pkg, 'NkwDiscItem').use(MC.RecordItem, MC.SoundEvent, MC.Item)
    const sig = p.recordLength ? 'int comparator, SoundEvent sound, Item.Properties properties, int seconds' : 'int comparator, SoundEvent sound, Item.Properties properties'
    const call = p.recordLength ? 'super(comparator, sound, properties, seconds);' : 'super(comparator, sound, properties);'
    out('NkwDiscItem', j.render(`public class NkwDiscItem extends RecordItem {\n    public NkwDiscItem(${sig}) {\n        ${call}\n    }\n}`))
  }

  if (modelBlocks.some((b) => !b.rotatable)) {
    const j = new JavaFile(pkg, 'NkwModelBlock').use(MC.Block, MC.BlockBehaviour, MC.BlockState, MC.BlockGetter, MC.BlockPos, MC.CollisionContext, MC.VoxelShape)
    out(
      'NkwModelBlock',
      j.render(`
public class NkwModelBlock extends Block {
    private final VoxelShape shape;

    public NkwModelBlock(BlockBehaviour.Properties properties, VoxelShape shape) {
        super(properties);
        this.shape = shape;
    }

    @Override
    public VoxelShape getShape(BlockState state, BlockGetter level, BlockPos pos, CollisionContext context) {
        return shape;
    }
}`)
    )
  }
  if (modelBlocks.some((b) => b.rotatable)) {
    const j = new JavaFile(pkg, 'NkwFacingModelBlock').use(
      MC.Block,
      MC.BlockBehaviour,
      MC.BlockState,
      MC.BlockGetter,
      MC.BlockPos,
      MC.CollisionContext,
      MC.VoxelShape,
      MC.Direction,
      MC.StateDefinition,
      MC.BlockStateProperties,
      MC.BlockPlaceContext,
      p.enumDirectionProperty ? MC.EnumProperty : MC.DirectionProperty
    )
    const propType = p.enumDirectionProperty ? 'EnumProperty<Direction>' : 'DirectionProperty'
    out(
      'NkwFacingModelBlock',
      j.render(`
public class NkwFacingModelBlock extends Block {
    public static final ${propType} FACING = BlockStateProperties.HORIZONTAL_FACING;
    private final VoxelShape north;
    private final VoxelShape east;
    private final VoxelShape south;
    private final VoxelShape west;

    public NkwFacingModelBlock(BlockBehaviour.Properties properties, VoxelShape north, VoxelShape east, VoxelShape south, VoxelShape west) {
        super(properties);
        this.north = north;
        this.east = east;
        this.south = south;
        this.west = west;
        registerDefaultState(this.stateDefinition.any().setValue(FACING, Direction.NORTH));
    }

    @Override
    protected void createBlockStateDefinition(StateDefinition.Builder<Block, BlockState> builder) {
        builder.add(FACING);
    }

    @Override
    public BlockState getStateForPlacement(BlockPlaceContext context) {
        return this.defaultBlockState().setValue(FACING, context.getHorizontalDirection().getOpposite());
    }

    @Override
    public VoxelShape getShape(BlockState state, BlockGetter level, BlockPos pos, CollisionContext context) {
        switch (state.getValue(FACING)) {
            case EAST: return east;
            case SOUTH: return south;
            case WEST: return west;
            default: return north;
        }
    }
}`)
    )
  }

  if (hasGeo) out('NkwGeoArmorItem', geckoArmorSource(ctx))

  // ───────── ModSounds ─────────
  {
    const j = new JavaFile(pkg, 'ModSounds').use(MC.SoundEvent)
    const factory = (idExpr: string) => (p.soundFactory ? `SoundEvent.createVariableRangeEvent(${idExpr})` : `new SoundEvent(${idExpr})`)
    let body: string
    if (fab) {
      j.use(MC.Registry, regImport, MC.RL)
      body = `
public final class ModSounds {
${ir.sounds.map((s) => `    public static final SoundEvent ${C(s.id)} = register("${s.id}");`).join('\n')}

    private ModSounds() {}

    private static SoundEvent register(String name) {
        ResourceLocation id = NkwMod.id(name);
        return Registry.register(${regSounds}, id, ${factory('id')});
    }

    public static void init() {}
}`
    } else {
      j.use(neo ? 'net.neoforged.neoforge.registries.DeferredRegister' : 'net.minecraftforge.registries.DeferredRegister')
      const holder = neo ? 'DeferredHolder<SoundEvent, SoundEvent>' : 'RegistryObject<SoundEvent>'
      j.use(neo ? 'net.neoforged.neoforge.registries.DeferredHolder' : 'net.minecraftforge.registries.RegistryObject')
      const create = neo ? 'DeferredRegister.create(Registries.SOUND_EVENT, NkwMod.MOD_ID)' : 'DeferredRegister.create(ForgeRegistries.SOUND_EVENTS, NkwMod.MOD_ID)'
      j.use(neo ? MC.Registries : 'net.minecraftforge.registries.ForgeRegistries')
      body = `
public final class ModSounds {
    public static final DeferredRegister<SoundEvent> SOUNDS = ${create};
${ir.sounds.map((s) => `    public static final ${holder} ${C(s.id)} = SOUNDS.register("${s.id}", () -> ${factory(`NkwMod.id("${s.id}")`)});`).join('\n')}

    private ModSounds() {}
}`
    }
    out('ModSounds', j.render(body))
  }

  // ───────── ModToolTiers ─────────
  if (ir.toolMats.length) out('ModToolTiers', toolTiers(ctx, ir.toolMats))

  // ───────── ModArmorMaterials ─────────
  if (ir.armorMats.length) out('ModArmorMaterials', armorMaterials(ctx, ir.armorMats))

  // ───────── ModBlocks ─────────
  out('ModBlocks', blocksClass(ctx))

  // ───────── ModItems ─────────
  out('ModItems', itemsClass(ctx, get))

  // ───────── ModTabs ─────────
  {
    const j = new JavaFile(pkg, 'ModTabs').use(MC.CreativeModeTab, MC.ItemStack)
    /** Java expression for any item id (mod item holder or a vanilla registry lookup). */
    const itemExpr = (id: string): string | null => {
      if (id.startsWith(`${ctx.ns}:`)) {
        const path = id.split(':')[1]
        return allItemIds.includes(path) ? get('ModItems', path) : null
      }
      j.use(regImport, MC.RL)
      const rl = p.rlFactory ? `ResourceLocation.parse("${id}")` : `new ResourceLocation("${id}")`
      return `${regItems}.${p.propertiesId ? 'getValue' : 'get'}(${rl})`
    }
    const iconFor = (tab: (typeof ir.tabs)[number]): string => {
      const fromItem = tab.icon ? itemExpr(tab.icon) : null
      if (fromItem) return `new ItemStack(${fromItem})`
      if (tab.logo) return `new ItemStack(${get('ModItems', `${tab.id}_tab_icon`)})`
      for (const id of tab.items) {
        const e = itemExpr(id)
        if (e) return `new ItemStack(${e})`
      }
      j.use(MC.Items)
      return 'new ItemStack(Items.BOOK)'
    }
    const accept = (tab: (typeof ir.tabs)[number], indent: string) =>
      tab.items
        .map((id) => itemExpr(id))
        .filter((e): e is string => !!e)
        .map((e) => `${indent}output.accept(${e});`)
        .join('\n')
    let body: string
    if (!p.tabRegistry) {
      if (fab) {
        j.use('net.fabricmc.fabric.api.client.itemgroup.FabricItemGroupBuilder')
        body = `
public final class ModTabs {
${ir.tabs.map((tb) => `    public static final CreativeModeTab ${C(tb.id)} = FabricItemGroupBuilder.build(NkwMod.id("${tb.id}"), () -> ${iconFor(tb)});`).join('\n')}

    private ModTabs() {}

    public static void init() {}
}`
      } else
        body = `
public final class ModTabs {
${ir.tabs
  .map(
    (tb) => `    public static final CreativeModeTab ${C(tb.id)} = new CreativeModeTab("${ctx.ns}_${tb.id}") {
        @Override
        public ItemStack makeIcon() {
            return ${iconFor(tb)};
        }
    };`
  )
  .join('\n')}

    private ModTabs() {}
}`
    } else if (fab) {
      j.use(MC.Registry, MC.BuiltIn, MC.Component, 'net.fabricmc.fabric.api.itemgroup.v1.FabricItemGroup')
      body = `
public final class ModTabs {
${ir.tabs
  .map(
    (tb) => `    public static final CreativeModeTab ${C(tb.id)} = Registry.register(BuiltInRegistries.CREATIVE_MODE_TAB, NkwMod.id("${tb.id}"),
        FabricItemGroup.builder()
            .icon(() -> ${iconFor(tb)})
            .title(Component.translatable("itemGroup.${ctx.ns}.${tb.id}"))
            .displayItems((parameters, output) -> {
${accept(tb, '                ')}
            })
            .build());`
  )
  .join('\n')}

    private ModTabs() {}

    public static void init() {}
}`
    } else {
      j.use(MC.Registries, MC.Component, neo ? 'net.neoforged.neoforge.registries.DeferredRegister' : 'net.minecraftforge.registries.DeferredRegister')
      j.use(neo ? 'net.neoforged.neoforge.registries.DeferredHolder' : 'net.minecraftforge.registries.RegistryObject')
      const holder = neo ? 'DeferredHolder<CreativeModeTab, CreativeModeTab>' : 'RegistryObject<CreativeModeTab>'
      body = `
public final class ModTabs {
    public static final DeferredRegister<CreativeModeTab> TABS = DeferredRegister.create(Registries.CREATIVE_MODE_TAB, NkwMod.MOD_ID);
${ir.tabs
  .map(
    (tb) => `    public static final ${holder} ${C(tb.id)} = TABS.register("${tb.id}", () -> CreativeModeTab.builder()
        .icon(() -> ${iconFor(tb)})
        .title(Component.translatable("itemGroup.${ctx.ns}.${tb.id}"))
        .displayItems((parameters, output) -> {
${accept(tb, '            ')}
        })
        .build());`
  )
  .join('\n')}

    private ModTabs() {}
}`
    }
    out('ModTabs', j.render(body))
  }

  // ───────── main class ─────────
  const count = `${ir.items.length + ir.blocks.length} items, ${ir.blocks.length} blocks, ${ir.sounds.length} sounds, ${ir.recipes.length} recipes`
  const idFn = p.rlFactory
    ? `public static ResourceLocation id(String path) {\n        return ResourceLocation.fromNamespaceAndPath(MOD_ID, path);\n    }`
    : `public static ResourceLocation id(String path) {\n        return new ResourceLocation(MOD_ID, path);\n    }`
  {
    const j = new JavaFile(pkg, 'NkwMod').use(MC.RL, MC.LogManager, MC.Logger)
    let body: string
    if (fab) {
      j.use('net.fabricmc.api.ModInitializer')
      body = `
public class NkwMod implements ModInitializer {
    public static final String MOD_ID = "${ctx.ns}";
    public static final Logger LOGGER = LogManager.getLogger(MOD_ID);

    ${idFn}

    @Override
    public void onInitialize() {
        NkwTags.init();
        ModSounds.init();
        ModBlocks.init();
        ModItems.init();
        ModTabs.init();
        LOGGER.info("[NKW] {} registered ${count}", MOD_ID);
    }
}`
    } else {
      const regs = [
        'ModSounds.SOUNDS',
        ...(p.armorApi === 'holder' && neo && ir.armorMats.length ? ['ModArmorMaterials.ARMOR_MATERIALS'] : []),
        'ModBlocks.BLOCKS',
        'ModItems.ITEMS',
        ...(p.tabRegistry ? ['ModTabs.TABS'] : [])
      ]
      const clientSetup = needsRenderLayer && !p.modelRenderType
      if (neo) j.use('net.neoforged.bus.api.IEventBus', 'net.neoforged.fml.common.Mod')
      else j.use('net.minecraftforge.eventbus.api.IEventBus', 'net.minecraftforge.fml.common.Mod', 'net.minecraftforge.fml.javafmlmod.FMLJavaModLoadingContext')
      if (clientSetup) j.use('net.minecraftforge.fml.event.lifecycle.FMLClientSetupEvent', MC.ItemBlockRenderTypes, MC.RenderType)
      const ctor = neo ? 'public NkwMod(IEventBus bus) {' : 'public NkwMod() {\n        IEventBus bus = FMLJavaModLoadingContext.get().getModEventBus();'
      body = `
@Mod(NkwMod.MOD_ID)
public class NkwMod {
    public static final String MOD_ID = "${ctx.ns}";
    public static final Logger LOGGER = LogManager.getLogger(MOD_ID);

    ${ctor}
        NkwTags.init();
${regs.map((r) => `        ${r}.register(bus);`).join('\n')}
${clientSetup ? '        bus.addListener(NkwMod::clientSetup);\n' : ''}        LOGGER.info("[NKW] {} registered ${count}", MOD_ID);
    }

    ${idFn}
${
  clientSetup
    ? `
    private static void clientSetup(FMLClientSetupEvent event) {
        event.enqueueWork(() -> {
${modelBlocks.map((b) => `            ItemBlockRenderTypes.setRenderLayer(ModBlocks.${C(b.id)}.get(), RenderType.cutout());`).join('\n')}
        });
    }`
    : ''
}
}`
    }
    out('NkwMod', j.render(body))
  }

  if (fab) {
    const j = new JavaFile(pkg, 'NkwClient').use('net.fabricmc.api.ClientModInitializer')
    if (needsRenderLayer) j.use('net.fabricmc.fabric.api.blockrenderlayer.v1.BlockRenderLayerMap', MC.RenderType)
    out(
      'NkwClient',
      j.render(`
public class NkwClient implements ClientModInitializer {
    @Override
    public void onInitializeClient() {
${modelBlocks.map((b) => `        BlockRenderLayerMap.INSTANCE.putBlock(ModBlocks.${C(b.id)}, RenderType.cutout());`).join('\n')}
    }
}`)
    )
  }
}

