/** Translatable text (`key` and `args` are Java expressions): TranslatableComponent before 1.19, Component.translatable after. */
export function translatable(p: VersionProfile, j: JavaFile, key: string, ...args: string[]): string {
  const a = args.map((x) => `, ${x}`).join('')
  if (p.mc === '1.16.5' || p.mc === '1.18.2') {
    j.use('net.minecraft.network.chat.TranslatableComponent')
    return `new TranslatableComponent(${key}${a})`
  }
  j.use(MC.Component)
  return `Component.translatable(${key}${a})`
}

/** The game's block or item registry: BuiltInRegistries (1.19.3+) or Registry. */
export function registry(p: VersionProfile, j: JavaFile, kind: 'BLOCK' | 'ITEM'): string {
  j.use(p.builtInRegistries ? MC.BuiltIn : MC.Registry)
  return `${p.builtInRegistries ? 'BuiltInRegistries' : 'Registry'}.${kind}`
}

/** Scheduled block ticks: the random type tick() takes, and the call that schedules a tick `ticks` from now. */
export function blockTicks(p: VersionProfile, j: JavaFile): { random: string; schedule: string } {
  const old = p.mc === '1.16.5' || p.mc === '1.18.2'
  j.use(old ? 'java.util.Random' : 'net.minecraft.util.RandomSource')
  return {
    random: old ? 'Random' : 'RandomSource',
    schedule: p.mc === '1.16.5' ? 'level.getBlockTicks().scheduleTick(pos, this, ticks)' : 'level.scheduleTick(pos, this, ticks)'
  }
}

/** Duration in ticks; infinite = -1 on 1.19.4+ (MobEffectInstance.INFINITE_DURATION), else max int. */
function effectTicks(e: EffectIR, p: VersionProfile): string {
  if (!e.infinite) return String(e.ticks)
  return p.smithingTransform ? '-1' : 'Integer.MAX_VALUE'
}
const HIT_ACTION = { fire: 'FIRE', lightning: 'LIGHTNING', freeze: 'FREEZE', teleport: 'TELEPORT', clear: 'CLEAR' } as const
/** `new NkwEffect(NkwEffect.FIRE, …)` arguments for a tool's on-hit abilities. */
const hitArgs = (list: HitIR[]) => list.map((h) => `, new NkwEffect(NkwEffect.${HIT_ACTION[h.ability]}, ${h.ticks}, ${f(h.chance)})`).join('')

/** `new NkwEffect(...)` expression for one effect. */
function effectExpr(e: EffectIR, p: VersionProfile): string {
  return `new NkwEffect(MobEffects.${e.effect}, ${effectTicks(e, p)}, ${e.amplifier}, ${f(e.chance)}, ${e.particles}, ${e.showIcon})`
}
const effectArgs = (list: EffectIR[], p: VersionProfile) => list.map((e) => `, ${effectExpr(e, p)}`).join('')

/** Armor constructor parameter types for the version's armor API. */
export function armorTypes(armorApi: string): { mat: string; slot: string; imports: string[] } {
  switch (armorApi) {
    case 'slot':
      return { mat: 'ArmorMaterial', slot: 'EquipmentSlot', imports: [MC.ArmorMaterialOld] }
    case 'type':
      return { mat: 'ArmorMaterial', slot: 'ArmorItem.Type', imports: [MC.ArmorMaterialOld] }
    case 'holder':
      return { mat: 'Holder<ArmorMaterial>', slot: 'ArmorItem.Type', imports: [MC.ArmorMaterialOld, MC.Holder] }
    default:
      return { mat: 'ArmorMaterial', slot: 'ArmorType', imports: [MC.ArmorMaterialNew, MC.ArmorType] }
  }
}

/** Java for "apply effects every second while this piece is worn". */
export function wornEffectsMethod(): string {
  return `    @Override
    public void inventoryTick(ItemStack stack, Level level, Entity entity, int slot, boolean selected) {
        super.inventoryTick(stack, level, entity, slot, selected);
        if (effects.length == 0 || level.isClientSide || level.getGameTime() % 20 != 0 || !(entity instanceof LivingEntity)) return;
        LivingEntity wearer = (LivingEntity) entity;
        if (wearer.getItemBySlot(wornSlot) != stack) return;
        for (NkwEffect effect : effects) effect.applyWorn(wearer);
    }`
}
