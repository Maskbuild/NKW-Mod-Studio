/**
 * The Forge / NeoForge game event bus for a target: which bus, the event package, how the player and
 * level getters are named on that version, and a server level-tick handler that calls tick(level).
 */
export function forgeEvents(ctx: GenCtx, j: JavaFile) {
  const neo = ctx.loader === 'neoforge'
  const old = !neo && (ctx.p.mc === '1.16.5' || ctx.p.mc === '1.18.2')
  const base = neo ? 'net.neoforged.neoforge' : 'net.minecraftforge'
  j.use(neo ? 'net.neoforged.neoforge.common.NeoForge' : 'net.minecraftforge.common.MinecraftForge')
  return {
    base,
    bus: neo ? 'NeoForge.EVENT_BUS' : 'MinecraftForge.EVENT_BUS',
    player: old ? 'getPlayer()' : 'getEntity()',
    level: old ? 'getWorld()' : 'getLevel()',
    /** `private static void onTick(…)` running tick(level) after every server level tick */
    tickHandler(): string {
      if (neo && ctx.p.jukeboxSongs) {
        j.use('net.neoforged.neoforge.event.tick.LevelTickEvent')
        return '    private static void onTick(LevelTickEvent.Post event) {\n        tick(event.getLevel());\n    }'
      }
      j.use(`${base}.event.TickEvent`)
      return `    private static void onTick(TickEvent.${old ? 'WorldTickEvent' : 'LevelTickEvent'} event) {\n        if (event.phase == TickEvent.Phase.END) tick(event.${old ? 'world' : 'level'});\n    }`
    }
  }
}

/**
 * What a jukebox does when one of our discs ends: pop it out, or play it again. Vanilla leaves the disc
 * in, so this class remembers the jukeboxes a player filled with such a disc and acts when the song
 * ends. Discs inserted by hoppers are not seen (there is no event for that) and behave like vanilla.
 */
function genJukebox(ctx: GenCtx, discs: ItemIR[], get: (cls: string, id: string) => string, out: (cls: string, text: string) => void): void {
  const { pkg, loader, p } = ctx
  const fab = fabricLike(loader)
  // how each era tells that the song ended, starts it again and pops the disc out
  const era = p.jukeboxSongs ? 'song' : p.mc.startsWith('1.20') ? 'record' : p.mc === '1.19.2' ? 'timer19' : 'timer'
  const timer = era === 'timer' || era === 'timer19'
  const j = new JavaFile(pkg, 'NkwJukebox').use(
    MC.Item,
    MC.ItemStack,
    MC.Level,
    MC.BlockPos,
    MC.BlockEntity,
    MC.JukeboxBlockEntity,
    'java.util.Iterator',
    'java.util.HashMap',
    'java.util.Map',
    'java.util.WeakHashMap'
  )
  if (timer) j.use(MC.BlockState, MC.JukeboxBlock, MC.ItemEntity)
  const current = era === 'song' ? 'jukebox.getTheItem()' : era === 'record' ? 'jukebox.getItem(0)' : 'jukebox.getRecord()'
  const ended =
    era === 'song'
      ? '!jukebox.getSongPlayer().isPlaying()'
      : era === 'record'
        ? '!jukebox.isRecordPlaying()'
        : 'level.getGameTime() - entry.getValue() >= ticks'
  const restart =
    era === 'song'
      ? 'jukebox.tryForcePlaySong();'
      : era === 'record'
        ? 'jukebox.startPlaying();'
        : `level.levelEvent(1010, pos, Item.getId(item));${era === 'timer19' ? '\n                    jukebox.playRecord();' : ''}
                    entry.setValue(level.getGameTime());`
  const eject = era === 'song' ? 'jukebox.popOutTheItem();' : era === 'record' ? 'jukebox.popOutRecord();' : 'eject(level, pos, jukebox);'

  let hooks: string
  if (fab) {
    j.use('net.fabricmc.fabric.api.event.player.UseBlockCallback', 'net.fabricmc.fabric.api.event.lifecycle.v1.ServerTickEvents', MC.InteractionResult)
    hooks = `    public static void init() {
        UseBlockCallback.EVENT.register((player, level, hand, hit) -> {
            onUse(level, hit.getBlockPos(), player.getItemInHand(hand));
            return InteractionResult.PASS;
        });
        ServerTickEvents.END_WORLD_TICK.register(level -> tick(level));
    }`
  } else {
    const ev = forgeEvents(ctx, j)
    j.use(`${ev.base}.event.entity.player.PlayerInteractEvent`)
    hooks = `    public static void init() {
        ${ev.bus}.addListener(NkwJukebox::onRightClick);
        ${ev.bus}.addListener(NkwJukebox::onTick);
    }

    private static void onRightClick(PlayerInteractEvent.RightClickBlock event) {
        onUse(event.${ev.level}, event.getPos(), event.getItemStack());
    }

${ev.tickHandler()}`
  }

  const ejectFn = timer
    ? `

    /** Same as taking the disc out by hand: stop the music, empty the jukebox, drop the disc on top. */
    private static void eject(Level level, BlockPos pos, JukeboxBlockEntity jukebox) {
        ItemStack stack = jukebox.getRecord().copy();
        level.levelEvent(1010, pos, 0);
        jukebox.clearContent();
        BlockState state = level.getBlockState(pos);
        level.setBlock(pos, state.setValue(JukeboxBlock.HAS_RECORD, false), 2);
        ItemEntity drop = new ItemEntity(level, pos.getX() + 0.5, pos.getY() + 1.01, pos.getZ() + 0.5, stack);
        drop.setDefaultPickUpDelay();
        level.addFreshEntity(drop);
    }`
    : ''

  out(
    'NkwJukebox',
    j.render(`
/** Pops our music discs out of jukeboxes, or plays them again, when the song ends. */
public final class NkwJukebox {
    /** level -> jukebox position -> game time the song (re)started */
    private static final Map<Level, Map<BlockPos, Long>> TRACKED = new WeakHashMap<>();

    private NkwJukebox() {}

${hooks}

    /** Song length in ticks for our discs, 0 for every other item. */
    private static int songTicks(Item item) {
${discs.map((d) => `        if (item == ${get('ModItems', d.id)}) return ${d.disc!.length * 20 + (d.disc!.onEnd === 'loop' ? 20 : 10)};`).join('\n')}
        return 0;
    }

    private static boolean loops(Item item) {
${discs
  .filter((d) => d.disc!.onEnd === 'loop')
  .map((d) => `        if (item == ${get('ModItems', d.id)}) return true;`)
  .join('\n')}
        return false;
    }

    private static void onUse(Level level, BlockPos pos, ItemStack held) {
        if (level.isClientSide || songTicks(held.getItem()) == 0) return;
        if (!(level.getBlockEntity(pos) instanceof JukeboxBlockEntity)) return;
        TRACKED.computeIfAbsent(level, l -> new HashMap<>()).put(pos.immutable(), level.getGameTime());
    }

    private static void tick(Level level) {
        if (level.isClientSide) return;
        Map<BlockPos, Long> jukeboxes = TRACKED.get(level);
        if (jukeboxes == null || jukeboxes.isEmpty()) return;
        Iterator<Map.Entry<BlockPos, Long>> it = jukeboxes.entrySet().iterator();
        while (it.hasNext()) {
            Map.Entry<BlockPos, Long> entry = it.next();
            BlockPos pos = entry.getKey();
            if (!level.isLoaded(pos)) continue;
            BlockEntity be = level.getBlockEntity(pos);
            if (!(be instanceof JukeboxBlockEntity)) {
                it.remove();
                continue;
            }
            JukeboxBlockEntity jukebox = (JukeboxBlockEntity) be;
            Item item = ${current}.getItem();
            int ticks = songTicks(item);
            if (ticks == 0) {
                it.remove();
                continue;
            }
            if (${ended}) {
                if (loops(item)) {
                    ${restart}
                } else {
                    ${eject}
                    it.remove();
                }
            }
        }
    }${ejectFn}
}`)
  )
}

/**
 * Thirst add-on for the thirst mods that only take values from code. Tough As Nails, Thirst Was Taken 2
 * and Legendary Survival Overhaul read data files instead (see genData). Everything goes through
 * reflection, so the mod neither needs nor ships the thirst mod and does nothing when it is absent.
 * - Thirst Was Taken (Forge 1.18.2–1.20.1, NeoForge 1.21.1): its RegisterThirstValueEvent.
 * - Thirsty (Fabric 1.20.1): entries added to its item list when a server starts.
 * Returns whether NkwThirst was written.
 */
function genThirst(ctx: GenCtx, get: (cls: string, id: string) => string, out: (cls: string, text: string) => void): boolean {
  const { ir, pkg, loader, p, ns } = ctx
  const items = ir.items.filter((it) => it.food?.thirst)
  if (!items.length) return false
  const neo = loader === 'neoforge'
  const twt = (loader === 'forge' && ['1.18.2', '1.19.2', '1.20.1'].includes(p.mc)) || (neo && p.mc === '1.21.1')
  const thirsty = fabricLike(loader) && p.mc === '1.20.1'
  if (!twt && !thirsty) return false
  const j = new JavaFile(pkg, 'NkwThirst')
  let body: string
  if (twt) {
    j.use(MC.Item, 'java.lang.reflect.Method', 'java.util.function.Consumer')
    j.use(neo ? 'net.neoforged.fml.ModList' : 'net.minecraftforge.fml.ModList')
    j.use(neo ? 'net.neoforged.bus.api.EventPriority' : 'net.minecraftforge.eventbus.api.EventPriority')
    const ev = forgeEvents(ctx, j)
    body = `
/** Thirst values for Thirst Was Taken, used only when it is installed. */
public final class NkwThirst {
    private NkwThirst() {}

    @SuppressWarnings({"unchecked", "rawtypes"})
    public static void init() {
        if (!ModList.get().isLoaded("thirst")) return;
        try {
            Class event = Class.forName("dev.ghen.thirst.foundation.common.event.RegisterThirstValueEvent");
            ${ev.bus}.addListener(EventPriority.NORMAL, false, event, (Consumer) NkwThirst::register);
        } catch (ReflectiveOperationException | LinkageError e) {
            NkwMod.LOGGER.warn("[NKW] Thirst Was Taken support is off: {}", e.toString());
        }
    }

    private static void register(Object event) {
        try {
            Method drink = event.getClass().getMethod("addDrink", Item.class, int.class, int.class);
            Method food = event.getClass().getMethod("addFood", Item.class, int.class, int.class);
${items.map((it) => `            ${it.food!.drink ? 'drink' : 'food'}.invoke(event, ${get('ModItems', it.id)}, ${it.food!.thirst!.thirst}, ${it.food!.thirst!.hydration});`).join('\n')}
            NkwMod.LOGGER.info("[NKW] thirst values added for ${items.length} item(s) (Thirst Was Taken)");
        } catch (ReflectiveOperationException e) {
            NkwMod.LOGGER.warn("[NKW] Could not add thirst values: {}", e.toString());
        }
    }
}`
  } else {
    j.use('java.lang.reflect.Field', MC.List, 'net.fabricmc.loader.api.FabricLoader', 'net.fabricmc.fabric.api.event.lifecycle.v1.ServerLifecycleEvents')
    body = `
/** Thirst values for Thirsty, used only when it is installed. */
public final class NkwThirst {
    private NkwThirst() {}

    public static void init() {
        if (FabricLoader.getInstance().isModLoaded("thirsty")) ServerLifecycleEvents.SERVER_STARTING.register(server -> thirsty());
    }

    @SuppressWarnings("unchecked")
    private static void thirsty() {
        try {
            Class<?> config = Class.forName("net.obe107.thirsty.config.ModConfig");
            Object instance = config.getMethod("getInstance").invoke(null);
            List<Object> items = (List<Object>) config.getField("customItems").get(instance);
            // an empty list gets Thirsty's defaults first
            if (items.isEmpty()) config.getMethod("validatePostLoad").invoke(instance);
            Class<?> entry = Class.forName("net.obe107.thirsty.config.ModConfig$ItemEntry");
            Field itemId = entry.getField("itemId");
${items.map((it) => `            add(items, entry, itemId, "${ns}:${it.id}", ${it.food!.thirst!.thirst}, ${it.food!.thirst!.hydration});`).join('\n')}
            config.getMethod("validatePostLoad").invoke(instance);
            NkwMod.LOGGER.info("[NKW] thirst values added for ${items.length} item(s) (Thirsty)");
        } catch (ReflectiveOperationException | LinkageError | ClassCastException e) {
            NkwMod.LOGGER.warn("[NKW] Thirsty support is off: {}", e.toString());
        }
    }

    private static void add(List<Object> items, Class<?> entry, Field itemId, String id, int thirst, int saturation) throws ReflectiveOperationException {
        for (Object o : items) if (id.equals(itemId.get(o))) return;
        items.add(entry.getConstructor(String.class, int.class, int.class).newInstance(id, thirst, saturation));
    }
}`
  }
  out('NkwThirst', j.render(body))
  return true
}

