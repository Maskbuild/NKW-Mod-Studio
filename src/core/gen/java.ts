const C = (id: string) => id.toUpperCase()
const f = (n: number) => `${Number.isInteger(n) ? n.toFixed(1) : String(n)}F`
const d = (n: number) => (Number.isInteger(n) ? n.toFixed(1) : String(n))

class JavaFile {
  imports = new Set<string>()
  constructor(
    readonly pkg: string,
    readonly name: string
  ) {}
  use(...cls: string[]) {
    for (const c of cls) this.imports.add(c)
    return this
  }
  render(body: string): string {
    const imps = [...this.imports].sort()
    return `// Generated by NKW Mod Studio (Nam Kueap Wan). Changes will be overwritten.\npackage ${this.pkg};\n\n${imps.map((i) => `import ${i};`).join('\n')}${imps.length ? '\n\n' : ''}${body.trim()}\n`
  }
}

