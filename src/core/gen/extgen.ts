import type { LoadedExtension } from '../ext/manifest'
import { extHost } from '../ext/host'
import { evalExpr, parseExpr, truthy, MATH_FNS, type ExprFn } from '../ext/expr'
import { extensionSupports, targetConfigFor } from '../ext/support'
import { parseTemplate, renderTemplate } from '../ext/tpl'
import { ASSET_RE } from '../project'
import { RES, fabricLike, forgeNames, json, type GenCtx } from './types'

/**
 * Runs the `generate` and `hooks` entries of the enabled extensions: renders their templates into Java
 * classes and files of the mod. Templates only see the data named in the manifest check (SCOPE_ROOTS) and a
 * few fixed helpers.
 */

/** Does any id in the mod (outside extension data) start with this prefix, e.g. "farmersdelight:". */
const anyUse = (ctx: Pick<GenCtx, 'ir'>): ExprFn => {
  let text: string | null = null
  return (prefix) => {
    text ??= JSON.stringify(ctx.ir, (k, v) => (k === 'ext' ? undefined : v))
    return typeof prefix === 'string' && prefix.length > 0 && text.includes(prefix)
  }
}

/** Folders of the data pack that differ between versions. */
function dataPaths(ctx: Pick<GenCtx, 'p'>) {
  const dir = (plural: string, singular: string) => (ctx.p.pluralDataDirs ? plural : singular)
  return {
    data: `${RES}/data`,
    itemTags: dir('tags/items', 'tags/item'),
    blockTags: dir('tags/blocks', 'tags/block'),
    recipes: dir('recipes', 'recipe')
  }
}

export function scopeFor(ctx: Pick<GenCtx, 'ir' | 'p' | 'loader' | 'target' | 'ns' | 'pkg'>, ext: LoadedExtension): Record<string, unknown> {
  const ir = { ...ctx.ir, ext: undefined }
  return {
    ir,
    ext: ctx.ir.ext[ext.manifest.id] ?? {},
    profile: ctx.p,
    loader: ctx.loader,
    mc: ctx.target.mc,
    meta: ctx.ir.meta,
    modId: ctx.ns,
    pkg: ctx.pkg,
    forge: forgeNames(ctx),
    paths: dataPaths(ctx),
    cfg: targetConfigFor(ext.manifest, ctx.loader, ctx.target.mc)
  }
}

export function genExtensions(ctx: GenCtx, out: (cls: string, text: string) => void): void {
  for (const ext of extHost.list()) {
    if (!extensionSupports(ext.manifest, ctx.loader, ctx.target.mc)) continue
    const deferred = !fabricLike(ctx.loader)
    const fns: Record<string, ExprFn> = {
      ...MATH_FNS,
      any: anyUse(ctx),
      /** how generated code reaches a registered object: ModItems.RUBY (Fabric) or ModItems.RUBY.get() */
      /** an ingredient ({item} or {tag}) as JSON text the way this version writes it */
      ing: (x) => {
        const i = x as { item?: string; tag?: string }
        return JSON.stringify(ctx.p.stringIngredients ? (i.item ?? `#${i.tag}`) : i.item !== undefined ? { item: i.item } : { tag: i.tag })
      },
      /** an item stack without a count as JSON text: {"id": …} or {"item": …} depending on the version */
      stack: (id) => JSON.stringify(ctx.p.stackId ? { id } : { item: id }),
      reg: (cls, id) => `${String(cls)}.${String(id).toUpperCase()}${deferred ? '.get()' : ''}`
    }
    const base = scopeFor(ctx, ext)
    const partials = ext.templates
    const run = (when: string | undefined, each: string | undefined, fn: (scope: Record<string, unknown>) => void) => {
      if (when && !truthy(evalExpr(parseExpr(when), { scope: base, fns }))) return
      if (!each) return fn(base)
      const list = evalExpr(parseExpr(each), { scope: base, fns })
      if (!Array.isArray(list)) return
      list.slice(0, 5000).forEach((item, i) => fn({ ...base, item, loop: { index: i, first: i === 0, last: i === list.length - 1 } }))
    }

    for (const g of ext.manifest.generate)
      run(g.when, g.each, (scope) => {
        for (const e of g.emit) {
          if (e.kind === 'copy') {
            const from = renderTemplate(parseTemplate(e.from, 'copy.from'), { scope, fns }).trim()
            const to = renderTemplate(parseTemplate(e.path, 'path'), { scope, fns })
            // a missing or odd file name is already reported as a problem of the project: nothing is copied
            if (!ASSET_RE.test(from)) continue
            if (to.includes('..') || to.startsWith('/')) throw new Error(`Extension "${ext.manifest.id}" tried to write "${to}"`)
            ctx.files.push({ path: to.startsWith('resources/') ? `${RES}/${to.slice(10)}` : to, copy: from })
            continue
          }
          const imports = new Set<string>()
          const body = renderTemplate(ext.templates[e.template], { scope, fns, partials, imports })
          if (e.kind === 'java') {
            const cls = renderTemplate(parseTemplate(e.class, 'class'), { scope, fns })
            const imps = [...imports].sort()
            out(
              e.package ? `${e.package}/${cls}` : cls,
              `// Generated by NKW Mod Studio (Nam Kueap Wan). Changes will be overwritten.\npackage ${e.package ? `${ctx.pkg}.${e.package}` : ctx.pkg};\n\n${imps.map((i) => `import ${i};`).join('\n')}${imps.length ? '\n\n' : ''}${body.trim()}\n`
            )
          } else if (e.kind === 'json') {
            const path = renderTemplate(parseTemplate(e.path, 'path'), { scope, fns })
            if (path.includes('..') || path.startsWith('/')) throw new Error(`Extension "${ext.manifest.id}" tried to write "${path}"`)
            let doc: unknown
            try {
              doc = JSON.parse(body)
            } catch (err) {
              throw new Error(`Extension "${ext.manifest.id}": ${e.template} did not make valid JSON for ${path} (${(err as Error).message})`)
            }
            ctx.files.push({ path: path.startsWith('resources/') ? `${RES}/${path.slice(10)}` : path, text: json(doc) })
          } else {
            const path = renderTemplate(parseTemplate(e.path, 'path'), { scope, fns })
            if (path.includes('..') || path.startsWith('/')) throw new Error(`Extension "${ext.manifest.id}" tried to write "${path}"`)
            ctx.files.push({ path: path.startsWith('resources/') ? `${RES}/${path.slice(10)}` : path, text: body })
          }
        }
      })

    for (const m of ext.manifest.mixins.filter((m) => !m.when || truthy(evalExpr(parseExpr(m.when), { scope: base, fns }))))
      ctx.files.push({
        path: `${RES}/${ctx.ns}.${m.name}.mixins.json`,
        text: json({
          required: true,
          minVersion: '0.8',
          package: `${ctx.pkg}.mixin`,
          compatibilityLevel: `JAVA_${ctx.p.java}`,
          ...(m.common.length ? { mixins: m.common } : {}),
          ...(m.client.length ? { client: m.client } : {}),
          ...(m.server.length ? { server: m.server } : {}),
          injectors: { defaultRequire: 1 }
        })
      })

    ext.manifest.hooks.forEach((h, i) =>
      run(h.when, h.each, (scope) => ctx.hooks.add(h.site, renderTemplate(ext.templates[`hook:${i}`], { scope, fns }).trim(), h.order))
    )
  }
}

/** Modrinth projects the enabled extensions want in test runs for this mod and target. */
export function extTestSlugs(ctx: Pick<GenCtx, 'ir' | 'p' | 'loader' | 'target' | 'ns' | 'pkg'>): string[] {
  const out: string[] = []
  for (const ext of extHost.list()) {
    if (!extensionSupports(ext.manifest, ctx.loader, ctx.target.mc)) continue
    const scope = scopeFor(ctx, ext)
    const fns: Record<string, ExprFn> = { ...MATH_FNS, any: anyUse(ctx) }
    for (const m of ext.manifest.testMods) {
      if (m.when && !truthy(evalExpr(parseExpr(m.when), { scope, fns }))) continue
      const slug = evalExpr(parseExpr(m.slug), { scope, fns })
      if (typeof slug === 'string' && /^[a-z0-9][a-z0-9_-]{0,63}$/.test(slug) && !out.includes(slug)) out.push(slug)
    }
  }
  return out
}

/** The Mixin config files the enabled extensions add for a target (for the mod's metadata). */
export function mixinConfigs(ctx: Pick<GenCtx, 'ir' | 'p' | 'ns' | 'pkg' | 'loader' | 'target'>): string[] {
  const out: string[] = []
  for (const ext of extHost.list()) {
    if (!extensionSupports(ext.manifest, ctx.loader, ctx.target.mc)) continue
    const scope = scopeFor(ctx, ext)
    const fns: Record<string, ExprFn> = { ...MATH_FNS, any: anyUse(ctx) }
    for (const m of ext.manifest.mixins) if (!m.when || truthy(evalExpr(parseExpr(m.when), { scope, fns }))) out.push(`${ctx.ns}.${m.name}.mixins.json`)
  }
  return out
}

/** Language entries the enabled extensions add: [key, English, Thai] (Thai may be empty). */
export function extLangEntries(ctx: Pick<GenCtx, 'ir' | 'p' | 'loader' | 'target' | 'ns' | 'pkg'>): [string, string, string][] {
  const out: [string, string, string][] = []
  for (const ext of extHost.list()) {
    if (!extensionSupports(ext.manifest, ctx.loader, ctx.target.mc)) continue
    const base = scopeFor(ctx, ext)
    const fns: Record<string, ExprFn> = { ...MATH_FNS, any: anyUse(ctx) }
    for (const l of ext.manifest.lang) {
      if (l.when && !truthy(evalExpr(parseExpr(l.when), { scope: base, fns }))) continue
      let list: unknown[] = [undefined]
      if (l.each) {
        const v = evalExpr(parseExpr(l.each), { scope: base, fns })
        list = Array.isArray(v) ? v.slice(0, 5000) : []
      }
      list.forEach((item, i) => {
        const scope = l.each ? { ...base, item, loop: { index: i, first: i === 0, last: i === list.length - 1 } } : base
        const r = (t: string) => renderTemplate(parseTemplate(t, 'lang'), { scope, fns })
        out.push([r(l.key), r(l.en), l.th === undefined ? '' : r(l.th)])
      })
    }
  }
  return out
}
