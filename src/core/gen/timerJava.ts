import { ANCHORS, PLACES, type Anim, type Fill, type TimerDoc, type TimerElement } from '../timerUi'

/**
 * The Java side of the timer window: `NkwTimerLayout`, a port of `resolveLayout` (src/core/timerUi.ts) that
 * uses nothing of Minecraft, and the code that builds each document as Java objects. The tests compile this
 * with the JDK and compare its output with the TypeScript layout, so the game draws what the editor shows.
 */

const ENUM = {
  type: { rect: 0, bar: 1, ring: 2, text: 3, image: 4 },
  show: { always: 0, harvest: 1, mining: 2, low: 3 },
  dir: { ltr: 0, rtl: 1, ttb: 2, btt: 3 },
  align: { left: 0, center: 1, right: 2 },
  prop: { opacity: 0, x: 1, y: 2, scale: 3, color: 4 },
  trigger: { time: 0, progress: 1, low: 2 },
  ease: { linear: 0, in: 1, out: 2, inOut: 3 },
  loop: { once: 0, repeat: 1, pingpong: 2 }
} as const

/** The pure layout class (package `pkg`). */
export function timerLayoutJava(pkg: string): string {
  return `// Generated by NKW Mod Studio (Nam Kueap Wan). Changes will be overwritten.
package ${pkg};

import java.util.ArrayList;
import java.util.List;

/** Lays out the timer window into drawing commands. Plain Java: no Minecraft classes, so it can be tested alone. */
public final class NkwTimerLayout {
    public static final int RECT = 0, BAR = 1, RING = 2, TEXT = 3, IMAGE = 4;
    public static final int C_RECT = 0, C_TEXT = 1, C_IMAGE = 2;
    private static final int LOW_TICKS = 60;
    // anchors: topLeft, top, topRight, left, center, right, bottomLeft, bottom, bottomRight
    private static final double[][] A9 = { { 0, 0 }, { 0.5, 0 }, { 1, 0 }, { 0, 0.5 }, { 0.5, 0.5 }, { 1, 0.5 }, { 0, 1 }, { 0.5, 1 }, { 1, 1 } };

    private NkwTimerLayout() {}

    /** a solid colour (rgb2 < 0) or a gradient */
    public static final class Fill {
        public int rgb, rgb2 = -1, alpha = 100, alphaTo = 100;
        public boolean vertical;

        public static Fill solid(int rgb, int alpha) {
            Fill f = new Fill();
            f.rgb = rgb;
            f.alpha = alpha;
            f.alphaTo = alpha;
            return f;
        }

        public static Fill linear(int rgb, int rgb2, boolean vertical, int alpha, int alphaTo) {
            Fill f = solid(rgb, alpha);
            f.rgb2 = rgb2;
            f.vertical = vertical;
            f.alphaTo = alphaTo;
            return f;
        }
    }

    public static final class Anim {
        public int prop, trigger, ease, loop, ticks, delay;
        public double from, to;
        public int fromRgb, toRgb;

        public static Anim num(int prop, int trigger, double from, double to, int ticks, int delay, int ease, int loop) {
            Anim a = new Anim();
            a.prop = prop;
            a.trigger = trigger;
            a.from = from;
            a.to = to;
            a.ticks = ticks;
            a.delay = delay;
            a.ease = ease;
            a.loop = loop;
            return a;
        }

        public static Anim color(int trigger, int fromRgb, int toRgb, int ticks, int delay, int ease, int loop) {
            Anim a = num(4, trigger, 0, 0, ticks, delay, ease, loop);
            a.fromRgb = fromRgb;
            a.toRgb = toRgb;
            return a;
        }
    }

    public static final class El {
        public int type, anchor, opacity, show;
        public double x, y, w, h;
        public Fill fill, back;
        public Anim[] anims = new Anim[0];
        // bar
        public int pad, dir;
        // bar / rect border (borderW 0 = none)
        public int borderW, borderRgb, borderAlpha;
        // ring
        public int radius, thickness;
        public double start;
        public boolean cw = true;
        // text
        public String text = "", textTh = "";
        public int color;
        public boolean shadow = true;
        public double scale = 1;
        public int align;
        // image
        public String asset = "";
        public int tint = -1, texW = 16, texH = 16;

        public El(int type, int anchor, double x, double y, double w, double h, int opacity, int show) {
            this.type = type;
            this.anchor = anchor;
            this.x = x;
            this.y = y;
            this.w = w;
            this.h = h;
            this.opacity = opacity;
            this.show = show;
        }
    }

    public static final class Doc {
        public final int place, w, h;
        public final double px, py;
        public final El[] els;

        public Doc(int place, double px, double py, int w, int h, El[] els) {
            this.place = place;
            this.px = px;
            this.py = py;
            this.w = w;
            this.h = h;
            this.els = els;
        }
    }

    public static final class In {
        public int sw, sh;
        public boolean harvest, th;
        public double progress, ticksLeft, time;
    }

    /** one drawing command (kind C_RECT, C_TEXT or C_IMAGE) */
    public static final class Cmd {
        public int kind, x1, y1, x2, y2, argb, el, align, w, h, tw, th;
        public String text, asset;
        public boolean shadow;
        public double scale;
    }

    /** The text of an element before {seconds} / {percent} / {bar} are filled in (a translation in the game). */
    public interface Texts {
        String template(int docIndex, int elIndex, El el);
    }

    private static double ease(int e, double t) {
        switch (e) {
            case 1:
                return t * t;
            case 2:
                return 1 - (1 - t) * (1 - t);
            case 3:
                return t < 0.5 ? 2 * t * t : 1 - 2 * (1 - t) * (1 - t);
            default:
                return t;
        }
    }

    private static int mix(int a, int b, double t) {
        int r0 = (a >> 16) & 255, g0 = (a >> 8) & 255, b0 = a & 255;
        int r1 = (b >> 16) & 255, g1 = (b >> 8) & 255, b1 = b & 255;
        int r = (int) Math.round(r0 + (r1 - r0) * t);
        int g = (int) Math.round(g0 + (g1 - g0) * t);
        int bl = (int) Math.round(b0 + (b1 - b0) * t);
        return (r << 16) | (g << 8) | bl;
    }

    private static int a255(int alphaPct, double opacityPct) {
        return (int) Math.round(Math.round(alphaPct * 255 / 100.0) * (opacityPct / 100));
    }

    private static int argb(int rgb, int a) {
        return (a << 24) | rgb;
    }

    /** seconds left with one decimal, rounding half up on the decimal digit */
    public static String seconds(double ticksLeft) {
        long tenths = Math.max(0L, (long) Math.floor(ticksLeft / 2 + 0.5));
        return (tenths / 10) + "." + (tenths % 10);
    }

    private static String tokens(String text, In in) {
        int filled = (int) Math.floor(10 * in.progress);
        StringBuilder bar = new StringBuilder();
        for (int i = 0; i < 10; i++) bar.append(i < filled ? '\\u25A0' : '\\u25A1');
        return text.replace("{bar}", bar).replace("{seconds}", seconds(in.ticksLeft)).replace("{percent}", String.valueOf((long) Math.floor(in.progress * 100)));
    }

    private static boolean visible(int show, In in) {
        return show == 0 || (show == 1 && in.harvest) || (show == 2 && !in.harvest) || (show == 3 && in.ticksLeft <= LOW_TICKS);
    }

    private static final class Anims {
        double opacity = -1;
        boolean hasOpacity;
        double dx, dy, scale = 1;
        int color = -1;
    }

    private static Anims animate(Anim[] anims, In in) {
        Anims out = new Anims();
        for (Anim a : anims) {
            double u;
            if (a.trigger == 1) u = in.progress;
            else {
                double t = in.time;
                if (a.trigger == 2) {
                    if (in.ticksLeft > LOW_TICKS) continue;
                    t = LOW_TICKS - in.ticksLeft;
                }
                double r = Math.max(0, t - a.delay) / a.ticks;
                if (a.loop == 1) u = r - Math.floor(r);
                else if (a.loop == 2) {
                    double m = r - 2 * Math.floor(r / 2);
                    u = m <= 1 ? m : 2 - m;
                } else u = Math.min(1, r);
            }
            u = ease(a.ease, Math.min(1, Math.max(0, u)));
            if (a.prop == 4) {
                out.color = mix(a.fromRgb, a.toRgb, u);
                continue;
            }
            double v = a.from + (a.to - a.from) * u;
            if (a.prop == 0) {
                out.opacity = Math.min(100, Math.max(0, v));
                out.hasOpacity = true;
            } else if (a.prop == 1) out.dx = v;
            else if (a.prop == 2) out.dy = v;
            else out.scale = v;
        }
        return out;
    }

    private static void rect(List<Cmd> out, double x1, double y1, double x2, double y2, int argb) {
        int a = (int) Math.round(x1), b = (int) Math.round(y1), c = (int) Math.round(x2), d = (int) Math.round(y2);
        if (c <= a || d <= b) return;
        Cmd cmd = new Cmd();
        cmd.kind = C_RECT;
        cmd.x1 = a;
        cmd.y1 = b;
        cmd.x2 = c;
        cmd.y2 = d;
        cmd.argb = argb;
        out.add(cmd);
    }

    /** clip: dir (-1 = none) and the length of the part that is drawn */
    private static void fill(List<Cmd> out, double x, double y, double w, double h, Fill f, double opacity, int colorOverride, int clipDir, double clipLen) {
        if (w <= 0 || h <= 0) return;
        int rgb = colorOverride >= 0 ? colorOverride : f.rgb;
        if (f.rgb2 < 0) {
            piece(out, x, y, x + w, y + h, rgb, a255(f.alpha, opacity), x, y, w, h, clipDir, clipLen);
            return;
        }
        double len = f.vertical ? h : w;
        int n = (int) Math.max(1, Math.min(64, len));
        for (int i = 0; i < n; i++) {
            double t = (i + 0.5) / n;
            double a0 = Math.round(i * len / n);
            double a1 = Math.round((i + 1) * len / n);
            int c = mix(rgb, f.rgb2, t);
            int alpha = (int) Math.round(f.alpha + (f.alphaTo - f.alpha) * t);
            if (f.vertical) piece(out, x, y + a0, x + w, y + a1, c, a255(alpha, opacity), x, y, w, h, clipDir, clipLen);
            else piece(out, x + a0, y, x + a1, y + h, c, a255(alpha, opacity), x, y, w, h, clipDir, clipLen);
        }
    }

    private static void piece(List<Cmd> out, double x1, double y1, double x2, double y2, int rgb, int a, double x, double y, double w, double h, int clipDir, double clipLen) {
        if (clipDir == 0) x2 = Math.min(x2, x + clipLen);
        else if (clipDir == 1) x1 = Math.max(x1, x + w - clipLen);
        else if (clipDir == 2) y2 = Math.min(y2, y + clipLen);
        else if (clipDir == 3) y1 = Math.max(y1, y + h - clipLen);
        if (x2 > x1 && y2 > y1 && a > 0) rect(out, x1, y1, x2, y2, argb(rgb, a));
    }

    private static void frame(List<Cmd> out, double x, double y, double w, double h, double pad, int bw, int rgb, int alpha, double opacity) {
        int al = a255(alpha, opacity);
        if (al <= 0 || w <= 0 || h <= 0) return;
        double p = pad + bw;
        int col = argb(rgb, al);
        rect(out, x - p, y - p, x + w + p, y - pad, col);
        rect(out, x - p, y + h + pad, x + w + p, y + h + p, col);
        rect(out, x - p, y - pad, x - pad, y + h + pad, col);
        rect(out, x + w + pad, y - pad, x + w + p, y + h + pad, col);
    }

    /** The commands that draw a document: place, size and elements in, drawing commands out. */
    public static List<Cmd> layout(Doc doc, int docIndex, In in, Texts texts) {
        List<Cmd> out = new ArrayList<>();
        int cx = (int) Math.floor(in.sw / 2.0), cy = (int) Math.floor(in.sh / 2.0);
        int bw = doc.w, bh = doc.h;
        double bx, by;
        switch (doc.place) {
            case 0:
                bx = cx - Math.floor(bw / 2.0);
                by = cy + 10;
                break;
            case 1:
                bx = cx - Math.floor(bw / 2.0);
                by = in.sh - 50 - bh;
                break;
            case 2:
                bx = cx - Math.floor(bw / 2.0);
                by = 10;
                break;
            case 3:
                bx = cx - Math.floor(bw / 2.0);
                by = cy - Math.floor(bh / 2.0);
                break;
            case 4:
                bx = 6;
                by = 6;
                break;
            case 5:
                bx = in.sw - 6 - bw;
                by = 6;
                break;
            case 6:
                bx = 6;
                by = in.sh - 6 - bh;
                break;
            default:
                bx = in.sw - 6 - bw;
                by = in.sh - 6 - bh;
        }
        bx += doc.px;
        by += doc.py;
        for (int index = 0; index < doc.els.length; index++) {
            El e = doc.els[index];
            if (!visible(e.show, in)) continue;
            Anims an = animate(e.anims, in);
            double opacity = an.hasOpacity ? an.opacity : e.opacity;
            if (opacity <= 0) continue;
            double ax = A9[e.anchor][0], ay = A9[e.anchor][1];
            double w = e.type == RING ? e.radius * 2 : e.w;
            double h = e.type == RING ? e.radius * 2 : e.h;
            double grow = an.scale;
            double baseX = bx + Math.floor(ax * bw) + e.x - Math.floor(ax * w) + an.dx;
            double baseY = by + Math.floor(ay * bh) + e.y - Math.floor(ay * h) + an.dy;
            double x = baseX, y = baseY;
            if (grow != 1 && e.type != TEXT) {
                double nw = Math.round(w * grow), nh = Math.round(h * grow);
                x = baseX - Math.floor((nw - w) / 2);
                y = baseY - Math.floor((nh - h) / 2);
                w = nw;
                h = nh;
            }
            switch (e.type) {
                case RECT:
                    if (e.borderW > 0) frame(out, x, y, w, h, 0, e.borderW, e.borderRgb, e.borderAlpha, opacity);
                    fill(out, x, y, w, h, e.fill, opacity, an.color, -1, 0);
                    break;
                case BAR: {
                    if (e.borderW > 0) frame(out, x, y, w, h, e.pad, e.borderW, e.borderRgb, e.borderAlpha, opacity);
                    if (e.back != null) fill(out, x - e.pad, y - e.pad, w + e.pad * 2, h + e.pad * 2, e.back, opacity, -1, -1, 0);
                    double full = e.dir <= 1 ? w : h;
                    double len = Math.round(full * in.progress);
                    fill(out, x, y, w, h, e.fill, opacity, an.color, e.dir, len);
                    break;
                }
                case RING: {
                    int radius = (int) Math.round(e.radius * grow);
                    double inner = Math.max(0, radius - e.thickness);
                    double ccx = x + radius, ccy = y + radius;
                    double startRad = e.start * Math.PI / 180;
                    int col = an.color >= 0 ? an.color : e.fill.rgb;
                    int colA = a255(e.fill.alpha, opacity);
                    int backRgb = e.back != null ? e.back.rgb : 0;
                    int backA = e.back != null ? a255(e.back.alpha, opacity) : 0;
                    for (int dy = -radius; dy < radius; dy++) {
                        int runStart = -radius;
                        int runColor = 0;
                        for (int dx = -radius; dx <= radius; dx++) {
                            int c = 0;
                            if (dx < radius) {
                                double pxx = dx + 0.5, pyy = dy + 0.5;
                                double d = StrictMath.sqrt(pxx * pxx + pyy * pyy);
                                if (d <= radius && d >= inner) {
                                    double angle = StrictMath.atan2(pxx, -pyy);
                                    if (angle < 0) angle += Math.PI * 2;
                                    angle -= startRad;
                                    if (angle < 0) angle += Math.PI * 2;
                                    if (!e.cw) angle = Math.PI * 2 - angle;
                                    c = angle / (Math.PI * 2) <= in.progress ? argb(col, colA) : argb(backRgb, backA);
                                }
                            }
                            if (c != runColor || dx == radius) {
                                if ((runColor >>> 24) != 0) rect(out, ccx + runStart, ccy + dy, ccx + dx, ccy + dy + 1, runColor);
                                runStart = dx;
                                runColor = c;
                            }
                        }
                    }
                    break;
                }
                case TEXT: {
                    String template = texts.template(docIndex, index, e);
                    String text = tokens(template, in);
                    double scale = e.scale * grow;
                    int al = a255(100, opacity);
                    int rgb = an.color >= 0 ? an.color : e.color;
                    double ty = baseY - Math.floor(ay * 8 * scale);
                    if (al > 0) {
                        Cmd c = new Cmd();
                        c.kind = C_TEXT;
                        c.el = index;
                        c.text = text;
                        c.x1 = (int) Math.round(baseX);
                        c.y1 = (int) Math.round(ty);
                        c.align = e.align;
                        c.argb = argb(rgb, al);
                        c.shadow = e.shadow;
                        c.scale = scale;
                        out.add(c);
                    }
                    break;
                }
                default: {
                    int al = a255(100, opacity);
                    int tint = e.tint >= 0 ? e.tint : 0xFFFFFF;
                    if (al > 0 && w > 0 && h > 0 && !e.asset.isEmpty()) {
                        Cmd c = new Cmd();
                        c.kind = C_IMAGE;
                        c.el = index;
                        c.asset = e.asset;
                        c.x1 = (int) Math.round(x);
                        c.y1 = (int) Math.round(y);
                        c.w = (int) Math.round(w);
                        c.h = (int) Math.round(h);
                        c.tw = e.texW;
                        c.th = e.texH;
                        c.argb = argb(tint, al);
                        out.add(c);
                    }
                }
            }
        }
        return out;
    }
}
`
}

const rgbInt = (hex: string) => `0x${hex.slice(1).toUpperCase()}`
const num = (n: number) => (Number.isInteger(n) ? `${n}.0` : String(n))

function javaFill(f: Fill): string {
  if (f.kind === 'linear' && f.to)
    return `NkwTimerLayout.Fill.linear(${rgbInt(f.color)}, ${rgbInt(f.to)}, ${!!f.vertical}, ${f.alpha}, ${f.alphaTo ?? f.alpha})`
  return `NkwTimerLayout.Fill.solid(${rgbInt(f.color)}, ${f.alpha})`
}

function javaAnim(a: Anim): string {
  const trig = ENUM.trigger[a.trigger]
  const ease = ENUM.ease[a.ease]
  const loop = ENUM.loop[a.loop]
  if (a.prop === 'color') {
    if (typeof a.from !== 'string' || typeof a.to !== 'string') return ''
    return `NkwTimerLayout.Anim.color(${trig}, ${rgbInt(a.from)}, ${rgbInt(a.to)}, ${a.ticks}, ${a.delay}, ${ease}, ${loop})`
  }
  if (typeof a.from !== 'number' || typeof a.to !== 'number') return ''
  return `NkwTimerLayout.Anim.num(${ENUM.prop[a.prop]}, ${trig}, ${num(a.from)}, ${num(a.to)}, ${a.ticks}, ${a.delay}, ${ease}, ${loop})`
}

export const javaString = (s: string) =>
  `"${s
    .replace(/[\\"]/g, (c) => `\\${c}`)
    .replace(/\n/g, '\\n')
    .replace(/[^\x20-\x7e]/g, (c) => `\\u${c.charCodeAt(0).toString(16).padStart(4, '0')}`)}"`

/**
 * The body of a Java method `static NkwTimerLayout.Doc name()` that builds a document (statements, indented by 8).
 * `assetName` turns a project asset into the name used for it in the game.
 */
export function timerDocJava(doc: TimerDoc, assetName: (asset: string) => string): string {
  const lines: string[] = [`        NkwTimerLayout.El[] els = new NkwTimerLayout.El[${doc.elements.length}];`, '        NkwTimerLayout.El e;']
  doc.elements.forEach((el: TimerElement, i) => {
    lines.push(
      `        e = new NkwTimerLayout.El(${ENUM.type[el.type]}, ${ANCHORS.indexOf(el.anchor)}, ${num(el.x)}, ${num(el.y)}, ${num(el.w)}, ${num(el.h)}, ${el.opacity}, ${ENUM.show[el.show]});`
    )
    const anims = el.anims.map(javaAnim).filter(Boolean)
    if (anims.length) lines.push(`        e.anims = new NkwTimerLayout.Anim[] { ${anims.join(', ')} };`)
    if (el.type === 'rect') {
      lines.push(`        e.fill = ${javaFill(el.fill)};`)
      if (el.border) lines.push(`        e.borderW = ${el.border.width}; e.borderRgb = ${rgbInt(el.border.color)}; e.borderAlpha = ${el.border.alpha};`)
    } else if (el.type === 'bar') {
      lines.push(`        e.fill = ${javaFill(el.fill)};`)
      if (el.back) lines.push(`        e.back = ${javaFill(el.back)};`)
      lines.push(`        e.pad = ${el.pad}; e.dir = ${ENUM.dir[el.dir]};`)
      if (el.border) lines.push(`        e.borderW = ${el.border.width}; e.borderRgb = ${rgbInt(el.border.color)}; e.borderAlpha = ${el.border.alpha};`)
    } else if (el.type === 'ring') {
      lines.push(`        e.fill = ${javaFill(el.fill)};`)
      if (el.back) lines.push(`        e.back = ${javaFill(el.back)};`)
      lines.push(`        e.radius = ${el.radius}; e.thickness = ${el.thickness}; e.start = ${num(el.start)}; e.cw = ${el.cw};`)
    } else if (el.type === 'text') {
      lines.push(
        `        e.text = ${javaString(el.text)}; e.textTh = ${javaString(el.textTh ?? '')}; e.color = ${rgbInt(el.color)}; e.shadow = ${el.shadow}; e.scale = ${num(el.scale)}; e.align = ${ENUM.align[el.align]};`
      )
    } else {
      lines.push(
        `        e.asset = ${javaString(assetName(el.asset))}; e.texW = ${el.texW}; e.texH = ${el.texH};${el.tint ? ` e.tint = ${rgbInt(el.tint)};` : ''}`
      )
    }
    lines.push(`        els[${i}] = e;`)
  })
  lines.push(
    `        return new NkwTimerLayout.Doc(${PLACES.indexOf(doc.place.at)}, ${num(doc.place.x)}, ${num(doc.place.y)}, ${doc.size.w}, ${doc.size.h}, els);`
  )
  return lines.join('\n')
}
