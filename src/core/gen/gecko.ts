import { WORN_IMPORTS, armorTypes, wornEffectsMethod } from './java'
import { fabricLike, type GenCtx } from './types'

/**
 * GeckoLib 3D armor item. Two API generations:
 *  - 1.20.1 (GeckoLib 4.4 API): Fabric RenderProvider / Forge IClientItemExtensions, manual prepForRender
 *  - 1.21.1 (GeckoLib 4.5+ API): unified GeoRenderProvider, GeckoLib prepares the renderer itself
 * Each piece can loop one animation and give status effects while worn.
 */
export function geckoArmorSource(ctx: GenCtx): string {
  const { pkg, p, loader } = ctx
  const legacy = p.mc === '1.20.1'
  const at = armorTypes(p.armorApi)
  const imports = [
    'net.minecraft.client.model.HumanoidModel',
    'net.minecraft.world.entity.EquipmentSlot',
    'net.minecraft.world.entity.LivingEntity',
    'net.minecraft.world.item.ArmorItem',
    'net.minecraft.world.item.Item',
    'net.minecraft.world.item.ItemStack',
    'java.util.function.Consumer',
    'software.bernie.geckolib.animatable.GeoItem',
    'software.bernie.geckolib.model.DefaultedItemGeoModel',
    'software.bernie.geckolib.renderer.GeoArmorRenderer',
    'software.bernie.geckolib.util.GeckoLibUtil',
    ...at.imports,
    ...WORN_IMPORTS
  ]
  const g = legacy ? 'software.bernie.geckolib.core' : 'software.bernie.geckolib'
  imports.push(
    `${g}.animatable.instance.AnimatableInstanceCache`,
    `${g}.animation.AnimatableManager`,
    `${g}.animation.AnimationController`,
    `${g}.animation.RawAnimation`
  )

  const modelExpr = 'new DefaultedItemGeoModel<>(NkwMod.id("armor/" + setId))'
  let renderer: string
  if (!legacy) {
    imports.push('software.bernie.geckolib.animatable.client.GeoRenderProvider')
    renderer = `
    @Override
    public void createGeoRenderer(Consumer<GeoRenderProvider> consumer) {
        consumer.accept(new GeoRenderProvider() {
            private GeoArmorRenderer<?> renderer;

            @Override
            public <T extends LivingEntity> HumanoidModel<?> getGeoArmorRenderer(T entity, ItemStack stack, EquipmentSlot slot, HumanoidModel<T> original) {
                if (this.renderer == null) this.renderer = new GeoArmorRenderer<NkwGeoArmorItem>(${modelExpr});
                return this.renderer;
            }
        });
    }`
  } else if (fabricLike(loader)) {
    imports.push('software.bernie.geckolib.animatable.client.RenderProvider', 'java.util.function.Supplier')
    renderer = `
    private final Supplier<Object> renderProvider = GeoItem.makeRenderer(this);

    @Override
    public void createRenderer(Consumer<Object> consumer) {
        consumer.accept(new RenderProvider() {
            private GeoArmorRenderer<?> renderer;

            @Override
            public HumanoidModel<LivingEntity> getHumanoidArmorModel(LivingEntity entity, ItemStack stack, EquipmentSlot slot, HumanoidModel<LivingEntity> original) {
                if (this.renderer == null) this.renderer = new GeoArmorRenderer<NkwGeoArmorItem>(${modelExpr});
                this.renderer.prepForRender(entity, stack, slot, original);
                return this.renderer;
            }
        });
    }

    @Override
    public Supplier<Object> getRenderProvider() {
        return this.renderProvider;
    }`
  } else {
    imports.push('net.minecraftforge.client.extensions.common.IClientItemExtensions')
    renderer = `
    @Override
    public void initializeClient(Consumer<IClientItemExtensions> consumer) {
        consumer.accept(new IClientItemExtensions() {
            private GeoArmorRenderer<?> renderer;

            @Override
            public HumanoidModel<?> getHumanoidArmorModel(LivingEntity entity, ItemStack stack, EquipmentSlot slot, HumanoidModel<?> original) {
                if (this.renderer == null) this.renderer = new GeoArmorRenderer<NkwGeoArmorItem>(${modelExpr});
                this.renderer.prepForRender(entity, stack, slot, original);
                return this.renderer;
            }
        });
    }`
  }

  return `// Generated by NKW Mod Studio (Nam Kueap Wan). Changes will be overwritten.
package ${pkg};

${[...new Set(imports)].sort().map((i) => `import ${i};`).join('\n')}

public class NkwGeoArmorItem extends ArmorItem implements GeoItem {
    private final AnimatableInstanceCache cache = GeckoLibUtil.createInstanceCache(this);
    private final String setId;
    private final RawAnimation loop;
    private final EquipmentSlot wornSlot;
    private final NkwEffect[] effects;

    public NkwGeoArmorItem(${at.mat} material, ${at.slot} type, Item.Properties properties, EquipmentSlot wornSlot, String setId, String animation, NkwEffect... effects) {
        super(material, type, properties);
        this.wornSlot = wornSlot;
        this.setId = setId;
        this.loop = animation == null ? null : RawAnimation.begin().thenLoop(animation);
        this.effects = effects;
    }
${renderer}

    @Override
    public void registerControllers(AnimatableManager.ControllerRegistrar controllers) {
        if (loop != null) controllers.add(new AnimationController<>(this, "nkw_loop", 0, state -> state.setAndContinue(loop)));
    }

    @Override
    public AnimatableInstanceCache getAnimatableInstanceCache() {
        return this.cache;
    }

${wornEffectsMethod()}
}
`
}
